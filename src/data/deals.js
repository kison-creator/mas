export function formatDealSize(size) {
  if (size >= 1000) return `$${(size / 1000).toFixed(1)}B`
  return `$${size}M`
}

export function getDaysOpen(deal) {
  const start = new Date(deal.startDate)
  const end = deal.closeDate ? new Date(deal.closeDate) : new Date()
  return Math.floor((end - start) / (1000 * 60 * 60 * 24))
}

export function getStats(dealList) {
  const active = dealList.filter((d) => !['Closed', 'Terminated'].includes(d.status))
  const closed = dealList.filter((d) => d.status === 'Closed')
  const totalValue = dealList.reduce((sum, d) => sum + d.dealSize, 0)
  const avgSize = dealList.length ? totalValue / dealList.length : 0
  const avgClose = closed.length
    ? closed.reduce((sum, d) => sum + getDaysOpen(d), 0) / closed.length
    : 0

  return {
    totalValue,
    activeDeals: active.length,
    avgSize,
    avgClose: Math.round(avgClose),
    totalDeals: dealList.length,
  }
}
